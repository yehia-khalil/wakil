package driver

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// The markers the machine section lives between.
//
// **Everything between them is overwritten, and the document says so to the
// reader who would otherwise edit it.** The human half of a runbook is prose
// the operator writes, and the two must be distinguishable by looking rather
// than by remembering which section was which.
const (
	MachineWalkOpen  = "<!-- machine-walk: generated by `make e2e-runbook`; everything between these markers is overwritten -->"
	MachineWalkClose = "<!-- /machine-walk -->"
)

// MachineWalk is the machine half of an acceptance runbook: what the harness
// walked, against which build, and whether the Cover rung's three conditions
// hold.
//
// **It is rendered from the records rather than typed.** The alternative was
// an agent reading a terminal and writing the numbers into the runbook, which
// is a hand-kept second answer to a question the filesystem already answers —
// and worse here than elsewhere, because the whole point of the Cover rung is
// that the operator trusts the machine-walked half without re-checking it. A
// section an agent wrote about its own work is the thing *"Never an agent"*
// guards against; a section generated from the run is not.
type MachineWalk struct {
	GeneratedAt time.Time
	// HeadCommit is the build being certified. Every record must describe it.
	HeadCommit string
	Dirty      bool
	// Corpus is every check file that exists. It is the denominator of the
	// table: a file with no record is a check nobody ran, and it gets a row
	// saying so rather than being left out.
	Corpus []string
	Runs   []RunRecord
	// Verdict is what `make e2e-new` proved. Nil means it never ran, which is
	// not the same as its having passed and must not render as one.
	Verdict *Verdict
	// Coverage is the standing audit's verdict, and CoverageErr is why there
	// is none.
	//
	// **A coverage question nothing answered is an unmet condition, never a
	// met one.** A nil here used to be skipped, so a walk whose denominator
	// was stale — the ordinary state of a tree nobody has run `make e2e` on —
	// printed *the surface it added carries checks* over a computation that
	// never happened. That is the flattering direction, which is the only one
	// that matters.
	Coverage    *CoverageReport
	CoverageErr error
	// Notes are what the audit said about its own inputs: a denominator
	// observed from a dirty tree, most often. They are printed with the
	// numbers they qualify.
	Notes []string
	// Proofs are the committed proofs (`ProofDir`), keyed by check base name,
	// and Blobs each corpus file's `git hash-object` now. Together they answer
	// for a check the current verdict does not cover (#305).
	Proofs map[string]Proof
	Blobs  map[string]string
	// Selection is what `make e2e` chose to run. A check it did not pick and
	// nothing ran on this build is owed to `make e2e-full`, not a fault —
	// but only when the record names this head and is not itself a full run.
	Selection *Selection
}

// Err is the Cover rung's verdict: every check the corpus holds ran green
// against this build, and every check this branch added was seen to fail
// against the merge-base.
//
// **Each condition is reported in its own words.** A rung that failed with one
// compound status would send its reader to the wrong one of three targets.
func (w MachineWalk) Err() error {
	faults := w.faults()
	if len(faults) == 0 {
		return nil
	}
	return fmt.Errorf("the Cover rung is not turned:\n  %s", joinLines(faults))
}

// faults is each unmet condition, in its own words.
func (w MachineWalk) faults() []string {
	var faults []string
	for _, file := range w.Corpus {
		record, state := w.stateOf(file)
		switch state {
		case neverRun:
			faults = append(faults, fmt.Sprintf(
				"%s was never run against this build, so nothing is known about it — "+
					"run `make e2e`", file))
		case anotherBuild:
			faults = append(faults, record.Err(w.HeadCommit).Error())
		case redWalk:
			faults = append(faults, fmt.Sprintf("%s is red: %s", file, record.Note))
		}
	}
	switch {
	case w.Verdict == nil:
		faults = append(faults, "`make e2e-new` has not run against this branch, so no check "+
			"here has been seen to fail — and a check that has never failed is not evidence")
	// **A record that does not say which build it describes is refused.** It
	// was the file's one unargued branch, and it was argued the wrong way:
	// treating an empty field as a match certifies this build from a record
	// that never named one.
	case w.Verdict.HeadCommit != w.HeadCommit:
		faults = append(faults, fmt.Sprintf(
			"the failability record was written against %s and this tree is on %s — "+
				"run `make e2e-new`",
			ShortCommit(w.Verdict.HeadCommit), ShortCommit(w.HeadCommit)))
	default:
		if err := w.Verdict.Err(); err != nil {
			faults = append(faults, err.Error())
		}
	}
	switch {
	case w.Coverage == nil && w.CoverageErr != nil:
		faults = append(faults, fmt.Sprintf(
			"coverage could not be computed, so nothing here says whether the surface this "+
				"branch added carries checks: %v", w.CoverageErr))
	case w.Coverage == nil:
		faults = append(faults, "coverage was not computed, so nothing here says whether the "+
			"surface this branch added carries checks — run `make e2e`, which ends in the gate")
	default:
		if err := w.Coverage.Err(); err != nil {
			faults = append(faults, err.Error())
		}
	}
	return faults
}

// Markdown renders the section, markers included.
//
// **A red walk renders too, and says it is red.** A generator that refused to
// write anything until everything was green would leave the runbook holding
// the last green run — which is to say, describing another build.
func (w MachineWalk) Markdown() string {
	var out strings.Builder
	out.WriteString(MachineWalkOpen + "\n\n")

	generated := w.GeneratedAt
	if generated.IsZero() {
		generated = time.Now().UTC()
	}
	faults := w.faults()
	if len(faults) == 0 {
		// **The failability clause states what was proved, not what the rung
		// asks for.** A branch that added no check has none that were seen to
		// fail, and a banner claiming otherwise would be vacuously true in the
		// one register — evidence — where that is worthless.
		proved := "this branch added no check, so there was none to prove failable"
		if w.Verdict.Proved() {
			proved = "every check this branch added was seen to fail against the merge-base"
		}
		if owed := w.Owed(); len(owed) > 0 {
			fmt.Fprintf(&out, "**The machine walk is green for the checks this branch reaches:** "+
				"the %d `make e2e` selected ran green against this build, %s, and the surface it "+
				"added carries checks. **%d check(s) are owed to `make e2e-full`**, which the night run covers on "+
				"`main` after the merge (`make e2e-night-status`).\n\n", len(w.Corpus)-len(owed), proved, len(owed))
			if len(w.Selection.Unmapped) > 0 {
				out.WriteString("Changed files no check maps to, which only the full run covers:\n\n")
				for _, file := range w.Selection.Unmapped {
					fmt.Fprintf(&out, "- `%s`\n", file)
				}
				out.WriteString("\n")
			}
		} else {
			fmt.Fprintf(&out, "**The machine walk is green:** every check ran against this build, "+
				"%s, and the surface it added carries checks.\n\n", proved)
		}
	} else {
		fmt.Fprintf(&out, "**The machine walk is red** — %d condition(s) of the Cover rung are "+
			"not met:\n\n```\n%s\n```\n\n", len(faults), strings.Join(faults, "\n"))
	}
	fmt.Fprintf(&out, "Walked by `make e2e` against %s, rendered %s by `make e2e-runbook`. "+
		"Re-render it with that target; edits between the markers are overwritten.\n\n",
		ShortCommit(w.HeadCommit), generated.Format("2006-01-02 15:04 UTC"))
	if w.Dirty {
		out.WriteString("**The tree carried uncommitted changes**, so these checks ran against " +
			"that tree rather than against the commit named above.\n\n")
	}

	out.WriteString("| Check | `make e2e` | Red against the base | Assertions | Evidence |\n")
	out.WriteString("|---|---|---|---|---|\n")
	for _, file := range w.Corpus {
		out.WriteString(w.row(file))
	}
	for _, record := range w.orphans() {
		fmt.Fprintf(&out, "| `%s` | — | — | — | a record for a check the corpus no longer holds |\n",
			record.File)
	}
	out.WriteString("\n")

	out.WriteString(w.failures())
	out.WriteString(w.failability())
	out.WriteString(w.coverage())
	out.WriteString("\n" + MachineWalkClose)
	return out.String()
}

// row renders one check file's line.
func (w MachineWalk) row(file string) string {
	record, state := w.stateOf(file)
	switch state {
	case neverRun:
		return fmt.Sprintf("| `%s` | **never run** | — | — | — |\n", filepath.Base(file))
	case owedToFull:
		return fmt.Sprintf("| `%s` | owed to `make e2e-full` | — | — | — |\n", filepath.Base(file))
	case anotherBuild:
		// **A record of another build lends this walk none of its numbers.** A
		// row showing four assertions beside "another build" invites exactly
		// the count that must not be made.
		return fmt.Sprintf("| `%s` | **another build** (%s) | — | — | — |\n",
			filepath.Base(file), ShortCommit(record.HeadCommit))
	}
	walked := "✓ exit 0"
	if state == redWalk {
		walked = fmt.Sprintf("**red**, exit %d", record.Exit)
	}
	evidence := "—"
	if state == redWalk && record.Evidence != "" {
		evidence = "`" + record.Evidence + "`"
	}
	return fmt.Sprintf("| `%s` | %s | %s | %d | %s |\n",
		filepath.Base(file), walked, w.redAgainstBase(file), record.Assertions, evidence)
}

// redAgainstBase renders one check's cell in the "red against the base" column.
func (w MachineWalk) redAgainstBase(file string) string {
	if w.Verdict == nil {
		return "**not proved**"
	}
	for _, check := range w.Verdict.Checks {
		if !sameCheckFile(check.File, file) {
			continue
		}
		switch {
		case check.Redirected:
			return "proved elsewhere: " + check.Reason
		case check.Missing:
			return "**never ran against the base**"
		case check.Red:
			return "✓ red vs " + ShortCommit(w.Verdict.BaseCommit)
		default:
			return "**passed against the base**"
		}
	}
	// A check this branch did not touch was proved on the branch that wrote
	// it. `make e2e-new` is right not to re-prove it, and that branch
	// committed its proof (#305): carried here, said to be a record rather
	// than this run's — and refused when the check has changed since.
	if proof, ok := w.Proofs[filepath.Base(file)]; ok {
		if proof.CheckBlob != "" && proof.CheckBlob == w.Blobs[file] {
			return fmt.Sprintf("✓ red vs %s, recorded %s",
				ShortCommit(proof.BaseCommit), proof.ProvedAt.UTC().Format("2006-01-02"))
		}
		return fmt.Sprintf("**proved red vs %s on an earlier version — not re-proved**",
			ShortCommit(proof.BaseCommit))
	}
	return "not new on this branch"
}

// failures puts a red check's own words in the document.
//
// **.context/ is gitignored**, so a section that cited only the evidence
// directory would cite nothing a reader of the repository can open — the
// lesson `agent-e2e-retrodiction.md` was written under.
func (w MachineWalk) failures() string {
	var lines []string
	for _, file := range w.Corpus {
		record, state := w.stateOf(file)
		if state != redWalk {
			continue
		}
		for _, check := range record.Checks {
			for _, failure := range check.Failures {
				lines = append(lines, "- "+failure)
			}
			// **What was gathered, by name, and what was not.** The artefacts
			// themselves cannot travel: a screenshot is binary and the
			// directory holding it is gitignored, so the most a document can
			// honestly carry is that it exists, where, and — when it does not
			// — why.
			if len(check.Evidence) > 0 {
				lines = append(lines, fmt.Sprintf("  - evidence: %s, under `%s/%s/` (gitignored)",
					strings.Join(check.Evidence, ", "), record.Evidence, check.Name))
			}
			for _, gap := range check.EvidenceGaps {
				lines = append(lines, "  - evidence not gathered: "+gap)
			}
		}
		for _, fatal := range record.Fatal {
			lines = append(lines, "- the run itself was unsound: "+fatal)
		}
		for _, note := range record.Quarantined {
			lines = append(lines, "- "+note)
		}
	}
	if len(lines) == 0 {
		return ""
	}
	return "**What went red, in the harness's own words:**\n\n" + strings.Join(lines, "\n") + "\n\n"
}

// failability renders the second of the rung's three conditions.
func (w MachineWalk) failability() string {
	if w.Verdict == nil {
		return "**`make e2e-new` has not run against this branch.** No check here has been seen " +
			"to fail, and a check that has never failed is not evidence.\n\n"
	}
	if !w.Verdict.Proved() {
		return fmt.Sprintf("**`make e2e-new` proved nothing against %s** — this branch added no "+
			"check. Whether it owed one is the coverage gate's question, below.\n\n",
			ShortCommit(w.Verdict.BaseCommit))
	}
	if err := w.Verdict.Err(); err != nil {
		return "**`make e2e-new` did not prove every new check failable:**\n\n```\n" +
			err.Error() + "\n```\n\n"
	}
	return fmt.Sprintf("**`make e2e-new` saw every check this branch added go red against %s.**\n\n",
		ShortCommit(w.Verdict.BaseCommit))
}

// coverage renders the third condition, and the machine-known half of the
// residue: surface no check can reach, each with the reason somebody gave.
func (w MachineWalk) coverage() string {
	if w.Coverage == nil {
		because := ""
		if w.CoverageErr != nil {
			because = "\n\n```\n" + w.CoverageErr.Error() + "\n```"
		}
		return "**Coverage is unknown**, so nothing here says whether the surface this branch " +
			"added carries checks. Run `make e2e`, which ends in the gate." + because + "\n\n"
	}
	var out strings.Builder
	for _, note := range w.Notes {
		out.WriteString("**" + note + "**\n\n")
	}
	if err := w.Coverage.Err(); err != nil {
		out.WriteString("**The coverage gate is red:**\n\n```\n" + err.Error() + "\n```\n\n")
	} else {
		out.WriteString("**Every action and control this branch added carries a check.** " +
			w.Coverage.NewSurfaceCount() + ".\n\n")
	}
	for _, line := range w.Coverage.Counts() {
		out.WriteString("- " + line + "\n")
	}
	out.WriteString("\n")
	if len(w.Coverage.Excused) > 0 {
		out.WriteString(fmt.Sprintf(
			"**%d piece(s) of surface no check can reach**, each with the reason given in `%s`:\n\n",
			len(w.Coverage.Excused), ExemptionFile))
		for _, gap := range w.Coverage.Excused {
			fmt.Fprintf(&out, "- `%s` — %s\n", gap.Name, gap.Reason)
		}
		out.WriteString("\n")
	}
	out.WriteString("**This section knows nothing about what a machine cannot see.** " +
		"The visual rulings and the live-provider question stay the operator's, permanently; " +
		"they are the human section below.\n")
	return out.String()
}

// recordFor finds the record of one check file.
func (w MachineWalk) recordFor(file string) (RunRecord, bool) {
	for _, record := range w.Runs {
		if sameCheckFile(record.File, file) {
			return record, true
		}
	}
	return RunRecord{}, false
}

// sameCheckFile reports whether two spellings name the same check.
//
// **Spelling drift must not read as absence, because absence is the
// flattering answer here.** A verdict row records the path `make e2e-new` was
// given and the corpus records the path a glob produced; a leading `./`, a
// trailing slash or an absolute path between the two would silently turn *this
// check was never proved failable* into *this check is not new on this branch*
// — the one substitution the proof-of-failability exists to refuse.
//
// The base name is enough to identify a check because the whole harness
// already keys on it: `LoadChecks` names a check `filepath.Base(path)`, and
// `Verdict.Add` matches the runner's outcomes by that name.
func sameCheckFile(a, b string) bool {
	if filepath.Clean(a) == filepath.Clean(b) {
		return true
	}
	return filepath.Base(a) == filepath.Base(b)
}

// walkState is what one check file's record amounts to, in the three states
// the rung distinguishes.
//
// **Derived once, because the verdict and the table that shows it must not
// drift.** `Err` and `row` each used to re-derive these, so a change to one
// could leave a green row under a red verdict.
type walkState int

const (
	// neverRun: no record at all.
	neverRun walkState = iota
	// anotherBuild: a record, of a commit that is not the one being certified.
	anotherBuild
	// owedToFull: not run on this build, and this build's selection did not
	// pick it — `make e2e-full` owes it.
	owedToFull
	// redWalk and greenWalk: a record of this build, and its exit status.
	redWalk
	greenWalk
)

func (w MachineWalk) stateOf(file string) (RunRecord, walkState) {
	record, ran := w.recordFor(file)
	onThisBuild := ran && record.Err(w.HeadCommit) == nil
	switch {
	case !onThisBuild && w.owes(file):
		return record, owedToFull
	case !ran:
		return record, neverRun
	case !onThisBuild:
		return record, anotherBuild
	case !record.Green():
		return record, redWalk
	default:
		return record, greenWalk
	}
}

// owes reports whether this build's selection left the file to the full run.
func (w MachineWalk) owes(file string) bool {
	s := w.Selection
	// Only a selection owes: a hand-named or full run left the rest unrun, and
	// a dirty tree's uncommitted edits were never selected for.
	return s != nil && s.HeadCommit == w.HeadCommit && s.Mode == SelectModeSelected &&
		!s.Dirty && !s.Has(file)
}

// Owed lists the corpus files left to `make e2e-full`.
func (w MachineWalk) Owed() []string {
	var owed []string
	for _, file := range w.Corpus {
		if _, state := w.stateOf(file); state == owedToFull {
			owed = append(owed, file)
		}
	}
	return owed
}

// orphans are records for check files the corpus no longer holds — a check
// that was deleted or renamed since it was last run. They are reported rather
// than dropped, because a row nobody explains is how a reader learns to
// distrust the table.
func (w MachineWalk) orphans() []RunRecord {
	inCorpus := map[string]bool{}
	for _, file := range w.Corpus {
		inCorpus[file] = true
	}
	var orphans []RunRecord
	for _, record := range w.Runs {
		if !inCorpus[record.File] {
			orphans = append(orphans, record)
		}
	}
	sort.Slice(orphans, func(i, j int) bool { return orphans[i].File < orphans[j].File })
	return orphans
}

// SpliceMachineWalk replaces the machine section of a runbook, leaving
// everything else exactly as it was.
//
// **A document with no markers is refused rather than guessed at.** Where the
// machine section belongs is a judgement about that runbook — before the ten,
// after the exit criterion, under a heading of its own — and a generator that
// picked a spot would be editing prose it does not understand. The refusal
// prints the two lines to paste instead.
func SpliceMachineWalk(document, section string) (string, error) {
	open := strings.Index(document, MachineWalkOpen)
	if open < 0 {
		return "", fmt.Errorf(
			"this document has no machine section to replace. Put these two lines where it "+
				"belongs, and run this again:\n\n%s\n%s", MachineWalkOpen, MachineWalkClose)
	}
	rest := document[open:]
	closes := strings.Index(rest, MachineWalkClose)
	if closes < 0 {
		return "", fmt.Errorf(
			"this document opens a machine section and never closes it, so replacing it would "+
				"swallow everything after it. Add the closing marker:\n\n%s", MachineWalkClose)
	}
	end := open + closes + len(MachineWalkClose)
	return document[:open] + section + document[end:], nil
}
