package driver

import (
	"fmt"
	"os"
	"path/filepath"
)

// LaunchdPATH is the PATH a bundled app inherits.
//
// **The harness must not improve on it, and that is the whole of 2c-iii's
// check 1.** `launchctl getenv PATH` is empty on this machine, so an app
// started from Finder gets the system default; the operator's own Wakil,
// started from a terminal, carries their entire interactive PATH. The fixture
// used to be launched with the harness's PATH — which is a terminal's — so
// every pane it opened inherited a rich environment the shipped app never
// has, and the one defect class no test can see was invisible here too.
//
// `ShellIntegration.swift` says the same thing from the other side: *"Without
// this, `which kubectl` fails in Wakil.app and succeeds in every test, because
// a test inherits a terminal's environment and the bundled app inherits
// launchd's."* A harness that inherits a terminal's environment is a test.
const LaunchdPATH = "/usr/bin:/bin:/usr/sbin:/sbin"

// Profile is the shell profile a fixture seeds into its own HOME, and the
// marker only that profile can put on a shell's PATH.
type Profile struct {
	// Dir is the directory the profile prepends to PATH. It is deliberately
	// NOT on the app's own launch PATH.
	Dir string
	// Marker and SecondMarker are the binaries' names — what a check asks the
	// shell to find. Two, because the runbook's check walks two.
	Marker       string
	SecondMarker string
}

// The binaries the seeded profile makes reachable.
//
// **Two, because 2c-iii's check 1 walks two** — `echo $PATH` and
// `which brew`, or in the runbook's own licence, "any two binaries the
// operator's shell profile puts on PATH but a bare `-i` shell would not". One
// marker plus a `$PATH` substring is not the same claim: a single lookup can
// succeed through a path element that arrived some other way.
//
// Distinctive names on purpose: a check asserts a shell found them, and a
// name that could collide with something real on the machine would let the
// check pass for the wrong reason.
const (
	MarkerBinary       = "wakil-e2e-profile-marker"
	SecondMarkerBinary = "wakil-e2e-profile-marker-two"
)

// SeedProfile writes a `.zprofile` into the fixture's HOME and the binary it
// makes reachable.
//
// **Why a seeded profile rather than the operator's `brew`.** 2c-iii's
// runbook already licenses the substitution — *"substitute any two binaries
// the operator's shell profile puts on PATH but a bare `-i` shell would
// not"* — and seeding them makes the check hermetic: it passes or fails on
// Wakil's behaviour rather than on what this machine happens to have
// installed.
//
// **It tests exactly the mechanism the shipped app needs.** Wakil generates
// its own zshrc under a ZDOTDIR it owns and sources the user's `.zprofile` by
// hand, because zsh reads `$ZDOTDIR/.zprofile` from WAKIL's directory and not
// the operator's (`ShellIntegration.swift`). Remove that one line and the
// pane's shell still works, still draws, still runs commands — and can no
// longer find anything the operator's profile put on PATH. That is the defect,
// and the marker is what catches it.
func SeedProfile(fixture Fixture) (Profile, error) {
	profile := Profile{
		Dir:          filepath.Join(fixture.Root, "profile-bin"),
		Marker:       MarkerBinary,
		SecondMarker: SecondMarkerBinary,
	}
	if err := os.MkdirAll(profile.Dir, 0o755); err != nil {
		return Profile{}, fmt.Errorf("seeding the profile bin: %w", err)
	}
	for _, name := range []string{profile.Marker, profile.SecondMarker} {
		body := "#!/bin/sh\n# Generated by the e2e harness. Reachable only through the seeded .zprofile.\necho " +
			name + "\n"
		if err := os.WriteFile(filepath.Join(profile.Dir, name), []byte(body), 0o755); err != nil {
			return Profile{}, fmt.Errorf("seeding %s: %w", name, err)
		}
	}
	// **`.zprofile`, not `.zshrc`, and that is the file that matters.** zsh
	// reads /etc/zprofile itself for a login shell — where path_helper runs —
	// but `$ZDOTDIR/.zprofile` comes from Wakil's own directory, so the
	// operator's is sourced by hand or not at all.
	zprofile := "# Generated by the e2e harness. This is the operator's .zprofile stood in for.\n" +
		"export PATH=" + profile.Dir + ":$PATH\n"
	if err := os.WriteFile(filepath.Join(fixture.Home, ".zprofile"), []byte(zprofile), 0o644); err != nil {
		return Profile{}, fmt.Errorf("seeding the profile: %w", err)
	}
	return profile, nil
}
