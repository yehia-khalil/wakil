import Foundation

/// The shell integration Wakil injects into every shell it opens.
///
/// **Wakil writes it because nothing else does.** SwiftTerm *consumes* OSC
/// 133 — `SemanticPrompt.swift` parses and stores the marks — and nothing
/// *emits* them. The shell has to, and no shell does by default.
///
/// **It is load-bearing for the charter, not a nicety.** Invariant 2 stops
/// holding by itself the moment the shell owns the input line: Wakil then
/// sees keystrokes, never a submitted command, so `term_run` has no
/// trigger and *"actions are the only mutation path"* fails at the window.
/// OSC 133 `C` is the report that rescues it.
///
/// **What each mark does here:**
/// - `A` — prompt start. Opens the region the operator types into.
/// - `B` — prompt end / input start, emitted from `PS1` itself.
/// - `C;wakil_cmd=<base64>` — a command started, carrying **the command
///   line**. The base64 is not decoration: a command containing `;`, a
///   newline or a `BEL` would otherwise end the sequence early, and the
///   command line is the one field here that is arbitrary operator text.
///   SwiftTerm parses `C` and `D` together and reads the remaining fields
///   as `k=`/click options, so an unknown key passes through it harmlessly
///   while Wakil's own scanner reads it.
/// - `D;<code>` — the command finished, carrying its exit code. **The code
///   reaches no public API of SwiftTerm** — confirmed by feeding `D;42`
///   and finding nothing (probe §4.4) — which is why Wakil scans the byte
///   stream for these itself rather than asking the terminal about them.
/// - OSC 7 — the live cwd, so a `cd` never leaves the header lying.
/// - OSC 1337 `WakilEdit=1` — this prompt's shell has `__wakil_replace`, the
///   edit command a selection on the input line is sent to (#365). Every
///   prompt, after `A`; bash 3.2 never sends it.
///
/// **The operator's own rc is sourced first**, so this pane is their shell
/// and not a stripped one. Sourcing order alone only defends against an rc
/// that sets `PS1` once, at load time. It does **not** defend against a
/// `precmd` hook — oh-my-zsh, powerlevel10k, starship, all mainstream —
/// that recomputes `PS1` on every prompt: measured, that erases the `B`
/// suffix on every cycle after the first, with `A`, `C` and `D` all still
/// present. So `B` is **not** appended once; `__wakil_apply_ps1_mark`
/// (zsh) re-appends it from inside `__wakil_precmd`, which — because
/// `add-zsh-hook` appends to the end of `precmd_functions` and Wakil's own
/// `add-zsh-hook precmd` call runs after the user's rc has already made
/// its own — always runs LAST, after whatever the operator's own hooks did
/// to `PS1` that cycle.
public func generatedRC(forShell shell: String) -> String {
    switch shell {
    case "zsh": return zshRC
    case "bash": return bashRC
    default: return ""
    }
}

private let zshRC = #"""
# Generated by Wakil for one terminal pane. Not edited by hand; not read
# by anything but the shell this pane opened.

# The operator's own configuration first, under their real ZDOTDIR, so
# this pane is their shell. Restored afterwards so subshells behave.
if [ -n "$WAKIL_USER_ZDOTDIR" ]; then
  ZDOTDIR="$WAKIL_USER_ZDOTDIR"
else
  ZDOTDIR="$HOME"
fi
# BOTH files, and .zprofile is the one that matters in the shipped app.
# zsh reads /etc/zprofile itself for a login shell — that is where
# path_helper runs — but $ZDOTDIR/.zprofile is read from WAKIL's
# directory, not the operator's, so their own is sourced here by hand.
# Without this, `which kubectl` fails in Wakil.app and succeeds in every
# test, because a test inherits a terminal's environment and the bundled
# app inherits launchd's.
[ -r "$ZDOTDIR/.zprofile" ] && source "$ZDOTDIR/.zprofile"
[ -r "$ZDOTDIR/.zshrc" ] && source "$ZDOTDIR/.zshrc"

__wakil_osc() { printf '\033]%s\007' "$1" }
__wakil_in_block=0
# The exact bytes appended to `PS1` for the `B` mark, wrapped in zsh's
# zero-width marker — kept in a variable so `__wakil_apply_ps1_mark` can
# find and strip a stale copy of ITSELF before re-appending, rather than
# accumulating one more every prompt a hook leaves `PS1` untouched.
__wakil_b_wrapped="%{$(printf '\033]133;B\007')%}"

# **Re-applied every cycle, not appended once.** A one-time `PS1=...`
# append at rc-load time is erased the moment any LATER `precmd` hook
# recomputes `PS1` from scratch — oh-my-zsh, powerlevel10k and starship
# all do this — which measured as `A`, `C` and `D` present but `B` gone
# from the second prompt on.
#
# **`${PS1%$__wakil_b_wrapped}`, not `${PS1:gs/$__wakil_b_wrapped/}`.**
# Measured: zsh's `:gs/pattern/repl/` does not expand a variable placed in
# the pattern slot at all — `${x:gs/$pat/repl/}` searches for the four
# literal characters `$`, `p`, `a`, `t`, so with a dynamic pattern (ours
# carries raw ESC/BEL bytes and can't be written as a literal) it never
# matches and silently strips nothing. The `%`-suffix-removal form DOES
# expand a variable there, so it is what strips our own previous mark
# before this cycle's copy is appended — which is what keeps a hook that
# leaves `PS1` untouched from growing one more `B` every prompt.
__wakil_apply_ps1_mark() {
  PS1="${PS1%$__wakil_b_wrapped}"
  PS1="${PS1}${__wakil_b_wrapped}"
}

__wakil_precmd() {
  local code=$?
  # D closes whatever C opened. The FIRST precmd of a session runs with no
  # C before it — `preexec` never fired yet, so `__wakil_in_block` is
  # still its initial 0 — and that D is skipped rather than emitted with
  # no command behind it: a block with no C is not one the pane can draw
  # anything for, and it is exactly the kind of `commandEnd` a caller
  # merely waiting for "any" would be fooled by before the real one.
  [ "$__wakil_in_block" = "1" ] && __wakil_osc "133;D;$code"
  __wakil_in_block=0
  # `:gs/%/%25/` for the same reason `__wakil_apply_ps1_mark` doesn't use
  # `//`: a literal `%` in a directory name (say, one literally named
  # `100%25`) would otherwise reach `URL(string:)` unescaped, which reads
  # it as ALREADY percent-encoded and decodes it back down to `100%` —
  # the directory's name, silently wrong. Spaces already survive the
  # scanner's `URL(string:)` parse, so `%` is the one character this pane
  # cannot pass through raw.
  __wakil_osc "7;file://${HOST}${PWD:gs/%/%25/}"
  __wakil_osc "133;A"
  # #365: tells the pane this prompt's shell has `__wakil_replace` — only
  # while the binding is still there. A plugin that rebuilds keymaps after
  # this rc, or `bindkey -d`, would otherwise leave the pane sending a
  # request whose BEL is send-break in emacs mode: the typed line, gone.
  [[ "$(bindkey -M main '\e[999~')" == *' __wakil_replace' ]] && __wakil_osc "1337;WakilEdit=1"
  # LAST: after the user's own precmd hooks (registered earlier in
  # `precmd_functions`, since Wakil's own `add-zsh-hook precmd` call below
  # runs after their rc already made its own) have had their chance to
  # rewrite `PS1` for this cycle.
  __wakil_apply_ps1_mark
}

__wakil_preexec() {
  __wakil_in_block=1
  __wakil_osc "133;C;wakil_cmd=$(printf '%s' "$1" | base64 | tr -d '\n')"
}

# **A command that ends the session with `exit` never sees a second
# precmd.** zsh does not run `precmd` on the way out — only on the way to
# another prompt — so a block a `preexec` opened and then `exit` (or the
# shell simply running off the end of its input) closes would otherwise
# never get its `D`. `zshexit` runs right before the process actually
# ends, with `$?` still the exiting status, so it is what closes a block
# that is still open at that point. A block that already closed normally
# leaves `__wakil_in_block` at 0, so a shell that exits from an ordinary
# prompt — not mid-command — emits no spurious extra `D`.
__wakil_on_exit() {
  local code=$?
  [ "$__wakil_in_block" = "1" ] && __wakil_osc "133;D;$code"
}

# #365: editing a selection on the input line. The pane sends
#   ESC[999~ <startDelta>;<endDelta>;<b64 expected>;<b64 replacement> BEL
# with offsets relative to CURSOR (the screen cursor sits on BUFFER[CURSOR],
# so both sides agree on it). A selection that began in the prompt has a
# negative start: that many leading characters of `expected` are prompt and
# are dropped. Past the end of BUFFER (autosuggestion text is POSTDISPLAY,
# not BUFFER) is clamped off. Anything that then fails to match BUFFER is
# ignored, never guessed at.
__wakil_b64d() { printf '%s' "$1" | base64 -d 2>/dev/null; printf x }
__wakil_replace() {
  # The operator's rc may set KSH_ARRAYS, SH_WORD_SPLIT and friends.
  emulate -L zsh
  local payload= key
  while read -k 1 key; do
    [[ $key == $'\a' ]] && break
    payload+=$key
    (( ${#payload} > 1048576 )) && return 0
  done
  local -a f
  f=("${(@s:;:)payload}")
  (( ${#f} == 4 )) || return 0
  [[ $f[1] == (-|)<-> && $f[2] == (-|)<-> ]] || return 0
  local expected="$(__wakil_b64d "$f[3]")" repl="$(__wakil_b64d "$f[4]")"
  expected=${expected%x} repl=${repl%x}
  local start=$(( CURSOR + ${f[1]} )) end=$(( CURSOR + ${f[2]} ))
  if (( start < 0 )); then expected=${expected:$(( -start ))}; start=0; fi
  (( end > ${#BUFFER} )) && end=${#BUFFER}
  (( start < end )) || return 0
  expected=${expected:0:$(( end - start ))}
  [[ ${BUFFER:$start:$(( end - start ))} == "$expected" ]] || return 0
  BUFFER="${BUFFER:0:$start}${repl}${BUFFER:$end}"
  CURSOR=$(( start + ${#repl} ))
  zle -R
}
zle -N __wakil_replace
for __wakil_km in main emacs viins vicmd; do
  bindkey -M $__wakil_km '\e[999~' __wakil_replace
done
unset __wakil_km

autoload -Uz add-zsh-hook
add-zsh-hook precmd __wakil_precmd
add-zsh-hook preexec __wakil_preexec
add-zsh-hook zshexit __wakil_on_exit

# No static `PS1=...` append here: `__wakil_precmd` calls
# `__wakil_apply_ps1_mark` on every cycle, INCLUDING the very first one —
# zsh runs `precmd` before the first prompt is drawn too — so a one-time
# append at load time would only be a copy `__wakil_apply_ps1_mark`
# immediately strips and re-adds; leaving it out avoids maintaining two
# places that both know the mark's wrapped form.
"""#

private let bashRC = #"""
# Generated by Wakil for one terminal pane. See ShellIntegration.swift.

# `--rcfile` is ignored for a login shell, so this pane's bash is
# interactive-but-not-login and the profile chain is sourced by hand.
# /etc/profile is where path_helper runs; without it PATH in the bundled
# app is launchd's and /opt/homebrew/bin is missing.
[ -r /etc/profile ] && . /etc/profile
for __wakil_profile in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
  if [ -r "$__wakil_profile" ]; then . "$__wakil_profile"; break; fi
done
unset __wakil_profile
[ -r "$HOME/.bashrc" ] && . "$HOME/.bashrc"

__wakil_osc() { printf '\033]%s\007' "$1"; }
__wakil_in_block=0
# Blocks `__wakil_preexec` from misreading the CHAINED tail of
# `PROMPT_COMMAND` (below) as a newly submitted command. See that trap's
# own doc comment for the failure this closes.
__wakil_suppress_preexec=0
# The history NUMBER at the moment this rc loaded — see `__wakil_preexec`
# for why the number, not just the text, has to be tracked.
__wakil_last_histnum=$(HISTTIMEFORMAT= history 1 2>/dev/null | sed -e 's/^[[:space:]]*\([0-9]*\).*/\1/')

# Split into a `before`/`after` pair around the operator's own chained
# `PROMPT_COMMAND`, rather than one function bracketing it. `$?` has to be
# read the instant the prompt cycle starts — before the operator's own
# chained command can run anything that changes it — so the `D`/OSC7 half
# runs FIRST; `A` (prompt open) is held until AFTER their chain has run,
# so it marks the point closest to the prompt actually being drawn.
__wakil_before_precmd() {
  local code=$?
  # `__wakil_suppress_preexec` goes up BEFORE anything else: the
  # operator's own chained `PROMPT_COMMAND` runs after this function
  # returns, at bash's TOP LEVEL (unlike statements inside this function,
  # which the DEBUG trap never sees without `functrace` — see
  # `__wakil_preexec`), so without this flag their chain is itself
  # subject to the trap and gets treated as a submitted command.
  __wakil_suppress_preexec=1
  # The FIRST precmd of a session runs with no preceding C — no command
  # has been submitted yet — and that D is skipped rather than emitted
  # with nothing behind it. See the same guard in the zsh rc above.
  [ "$__wakil_in_block" = "1" ] && __wakil_osc "133;D;$code"
  __wakil_in_block=0
  # `${PWD//%/%25}` — plain bash, unlike zsh's `${var//%/...}`, reads a
  # bare `%` in this position as a literal character rather than an
  # anchor flag, so the substitution works as written here. A literal `%`
  # in a directory name (one named `100%25`, say) would otherwise reach
  # `URL(string:)` unescaped, which reads it as ALREADY percent-encoded
  # and decodes it back down to `100%` — the directory's real name,
  # silently wrong. Spaces already survive the scanner's `URL(string:)`
  # parse, so `%` is the one character this pane cannot pass through raw.
  __wakil_osc "7;file://${HOSTNAME}${PWD//%/%25}"
}

__wakil_after_precmd() {
  __wakil_osc "133;A"
  # Only while the binding is still there — see zsh's `__wakil_precmd`.
  [ "$__wakil_edit_supported" = "1" ] && [[ $(bind -X 2>/dev/null) == *__wakil_replace* ]] \
    && __wakil_osc "1337;WakilEdit=1"
  # Lowered LAST, once the operator's own chained `PROMPT_COMMAND` (which
  # ran between `__wakil_before_precmd` and here) can no longer be
  # mistaken for a submitted command.
  __wakil_suppress_preexec=0
}

# The DEBUG trap fires for EVERY simple command, including each stage of a
# pipeline and the prompt command itself. The flag is what makes one
# submitted command one block: the first command after a prompt opens it,
# and precmd closes it.
#
# **The command line comes from `history 1`'s TEXT, verified against its
# NUMBER — not `$BASH_COMMAND`, and not `history 1`'s text alone.**
# `$BASH_COMMAND` at this point is only the FIRST simple command of the
# line — for `printf hello; exit 7` it is `printf hello`, dropping
# everything after the first `;` — because the DEBUG trap fires once per
# simple command, while the operator submitted one line. Bash appends a
# whole interactive line to history as soon as it is read, before any of
# it runs, so `history 1` at the first DEBUG trap of that line normally
# already holds the exact text the operator typed — **but `history 1` is
# a different oracle: it reports what bash RECORDED, not what is about to
# run**, and those two diverge under entirely mainstream configuration.
# Measured, with `HISTIGNORE='ls:exit'` and `HISTCONTROL=ignorespace` set
# (both common) and the input `echo one` / `ls` / ` echo spaced` /
# `echo three`: `ls` and the space-led `echo spaced` are never appended to
# history at all, so `history 1` at their DEBUG trap still shows the
# PREVIOUS entry, `echo one` — two blocks labelled `echo one` when only
# one `echo one` ever ran, each carrying the OTHER command's exit code.
# That is worse than `$BASH_COMMAND`'s truncation: a plausible-but-false
# command reads, to both the operator and an agent, as what ran.
#
# The fix is to check whether `history 1` actually ADVANCED — its leading
# NUMBER, not just its text — since the last block. `ls` and
# ` echo spaced` leave the number unchanged, so the emitted command is the
# honest empty string rather than a stale one. This also closes the
# quieter case measured alongside it: with history disabled entirely
# (`set +o history` / `HISTSIZE=0`) AND a `HISTFILE` inherited from
# Wakil's own environment, `history 1` can return a line left behind by a
# DIFFERENT shell that happens to share that file — the number captured
# once at rc-load time (above) never advances after that, so every real
# command after the first is correctly reported as empty rather than as
# whatever that foreign entry says.
__wakil_preexec() {
  [ -n "$COMP_LINE" ] && return
  [ "$__wakil_suppress_preexec" = "1" ] && return
  [ "$__wakil_in_block" = "1" ] && return
  case "$BASH_COMMAND" in __wakil_*) return ;; esac
  __wakil_in_block=1
  local __wakil_entry __wakil_num __wakil_line
  __wakil_entry=$(HISTTIMEFORMAT= history 1 2>/dev/null)
  __wakil_num=$(printf '%s\n' "$__wakil_entry" | sed -e 's/^[[:space:]]*\([0-9]*\).*/\1/')
  if [ -n "$__wakil_num" ] && [ "$__wakil_num" != "$__wakil_last_histnum" ]; then
    __wakil_last_histnum="$__wakil_num"
    __wakil_line=$(printf '%s\n' "$__wakil_entry" | sed -e 's/^[[:space:]]*[0-9]*[[:space:]]*//')
  else
    # Honest empty beats a stale-but-plausible command: history did not
    # advance, so nothing here is proof of what is actually running.
    __wakil_line=""
  fi
  __wakil_osc "133;C;wakil_cmd=$(printf '%s' "$__wakil_line" | base64 | tr -d '\n')"
}

# **A command that ends the session with `exit` never sees a second
# `PROMPT_COMMAND`.** `exit` inside a block bash is executing — for
# instance the second half of `printf hello; exit 7` — terminates the
# process before `PROMPT_COMMAND` runs again, so the `D` that closes the
# block never fires there. Bash still honours an `EXIT` trap on the way
# out, with `$?` the exiting status, so that is what closes a block still
# open at that point. A shell exiting from an ordinary prompt has already
# closed its block, so `__wakil_in_block` is 0 there and this stays quiet.
__wakil_on_exit() {
  local code=$?
  [ "$__wakil_in_block" = "1" ] && __wakil_osc "133;D;$code"
}

# \[...\] is bash's zero-width marker, the counterpart of zsh's %{...%}.
# Set BEFORE the DEBUG trap below: a bare assignment is itself a "simple
# command" bash's DEBUG trap fires for, so installing the trap first made
# this very line open a phantom block — `preexec` firing on `PS1=...`
# itself, with no real command behind it, immediately followed by a
# `precmd` that closed it with whatever `$?` happened to be. That phantom
# `C`/`D` pair was hard to see in a person's terminal — one extra empty
# block, gone in a redraw — but it made a scripted test racing the very
# first prompt genuinely nondeterministic: `waitUntil` stops at the FIRST
# `commandEnd` it finds, and under load the phantom one could arrive
# before the real command's.
PS1="${PS1}\[$(printf '\033]133;B\007')\]"

# **Preserve whatever DEBUG trap the operator's own rc already installed**
# — bash-preexec, iTerm2's own shell integration — rather than silently
# replacing it, which contradicted this file's own claim that this pane
# is the operator's shell and not a stripped one (measured: a `.bashrc`
# setting `trap '...' DEBUG` never ran again once Wakil's `trap` line
# below overwrote it). `trap -p DEBUG` prints its answer as re-executable
# syntax — `trap -- 'command' DEBUG` — so stripping the fixed `trap -- `
# prefix and ` DEBUG` suffix leaves an still-correctly-quoted string, and
# `eval`-assigning THAT reconstructs the original command text intact
# even if it contains its own quoting.
__wakil_prior_debug_trap=$(trap -p DEBUG)
__wakil_prior_debug_cmd=""
if [ -n "$__wakil_prior_debug_trap" ]; then
  __wakil_prior_debug_quoted=${__wakil_prior_debug_trap#trap -- }
  __wakil_prior_debug_quoted=${__wakil_prior_debug_quoted% DEBUG}
  eval "__wakil_prior_debug_cmd=$__wakil_prior_debug_quoted"
fi
unset __wakil_prior_debug_trap __wakil_prior_debug_quoted

# **`[[ ... ]]`, not `[ ... ]`.** bash sets `$_` to the last argument of
# the previous SIMPLE command, and `[ ... ]` — `test`'s bracket form — is
# a simple command whose own last argument is the literal `]`. Running
# that here, between the trap's restore of `$_` (below) and the `eval`
# that hands the prior trap ITS `$_`, would silently clobber the restore
# with `]` again. `[[ ... ]]` is a shell keyword, not a simple command,
# so it leaves `$_` exactly as the trap line set it.
__wakil_run_prior_debug() {
  [[ -n "$__wakil_prior_debug_cmd" ]] && eval "$__wakil_prior_debug_cmd"
}

# **Prepended, not assigned** — same reason, measured the same way: a
# `.bashrc` setting `PROMPT_COMMAND='echo USER_PC_RAN'` never ran once
# Wakil's own assignment replaced it outright. Wakil's own precmd halves
# run first (`__wakil_before_precmd` needs `$?` before the operator's own
# chain can touch it) and last (`__wakil_after_precmd` needs to run once
# their chain — which their prompt-computing tools may depend on for
# `PS1` — is done), with their original `PROMPT_COMMAND` sandwiched
# between the two so it keeps running exactly where it always did.
#
# `trap ... DEBUG` last, and EXIT before it, not after: EVERY line below
# `trap ... DEBUG` is itself a simple command the trap it just installed
# would fire for — trap installation is not exempt from a trap it did not
# establish itself, only from the ONE line that establishes it. An `EXIT`
# trap installed after `DEBUG` learned this the hard way: that line
# opened a phantom block (`__wakil_preexec` firing on `BASH_COMMAND` of
# `trap ... EXIT`, uncaught by the `__wakil_*` filter since it does not
# start with `__wakil_`) which the next `precmd` then closed with
# `$?`\ =0 — a `commandStart("")` / `commandEnd(0)` pair with no real
# command behind it, present on every session. In a person's terminal it
# is one blank block, gone in a redraw; in `waitUntil`, which stops at the
# FIRST `commandEnd` it finds, it raced the real one and could win.
# #365: the same edit command as zsh's `__wakil_replace`, through
# READLINE_LINE / READLINE_POINT — bash 4 and later only. macOS's own
# /bin/bash is 3.2, has neither, gets no binding and never sends the signal.
__wakil_edit_supported=0
if (( ${BASH_VERSINFO[0]:-0} >= 4 )); then
  __wakil_b64d() { printf '%s' "$1" | base64 -d 2>/dev/null; printf x; }
  __wakil_replace() {
    local payload f1 f2 f3 f4 expected repl start end
    IFS= read -r -d $'\a' payload || return 0
    IFS=';' read -r f1 f2 f3 f4 <<< "$payload"
    [[ $f1 =~ ^-?[0-9]+$ && $f2 =~ ^-?[0-9]+$ ]] || return 0
    expected=$(__wakil_b64d "$f3"); expected=${expected%x}
    repl=$(__wakil_b64d "$f4"); repl=${repl%x}
    start=$(( READLINE_POINT + f1 )); end=$(( READLINE_POINT + f2 ))
    if (( start < 0 )); then expected=${expected:$(( -start ))}; start=0; fi
    (( end > ${#READLINE_LINE} )) && end=${#READLINE_LINE}
    (( start < end )) || return 0
    expected=${expected:0:$(( end - start ))}
    [[ "${READLINE_LINE:$start:$(( end - start ))}" == "$expected" ]] || return 0
    READLINE_LINE="${READLINE_LINE:0:$start}${repl}${READLINE_LINE:$end}"
    READLINE_POINT=$(( start + ${#repl} ))
  }
  bind -x '"\e[999~": __wakil_replace'
  __wakil_edit_supported=1
fi
PROMPT_COMMAND="__wakil_before_precmd${PROMPT_COMMAND:+;$PROMPT_COMMAND};__wakil_after_precmd"
trap '__wakil_on_exit' EXIT
# **`$_` is captured and restored around `__wakil_preexec`, not just the
# trap command itself preserved.** `$_` is the ONE piece of state a
# DEBUG trap can read about the command that is about to run other than
# `$BASH_COMMAND` — bash-preexec's own trap is exactly
# `'__bp_preexec_invoke_exec "$_"'` — and `__wakil_preexec`'s own guard
# clauses (`[ ... ] && return`) each overwrite `$_` with `]` as a side
# effect of running `test`'s bracket form. Without the save/restore here,
# the prior trap measured receiving `]` in place of the real `$_`.
# `__wakil_dollar_underscore=$_` is a bare assignment, which — unlike a
# command with arguments — does NOT itself update `$_`, so the value
# captured here is exactly what `$_` held before this trap line ran;
# `: "$__wakil_dollar_underscore"` (`:` is a builtin, this counts as a
# simple command) is what writes it back for the prior trap to read.
trap '__wakil_dollar_underscore=$_; __wakil_preexec; : "$__wakil_dollar_underscore"; __wakil_run_prior_debug' DEBUG
"""#

/// The argv and the extra environment for one shell, given a directory
/// Wakil has already written the generated rc into.
///
/// **zsh and bash take the rc by different routes**, and neither is
/// optional. zsh reads `$ZDOTDIR/.zshrc` for an interactive shell, so the
/// rc is written as `.zshrc` in a Wakil-owned directory and the operator's
/// real `ZDOTDIR` is passed through for the rc itself to restore. bash has
/// `--rcfile`, which is simpler and does the same job.
public func shellLaunch(
    shell: String, rcDirectory: URL,
    base: [String: String] = ProcessInfo.processInfo.environment
) throws -> (argv: [String], environment: [String: String]) {
    let name = (shell as NSString).lastPathComponent
    try FileManager.default.createDirectory(at: rcDirectory, withIntermediateDirectories: true)
    switch name {
    case "zsh":
        let rc = rcDirectory.appendingPathComponent(".zshrc")
        try generatedRC(forShell: "zsh").write(to: rc, atomically: true, encoding: .utf8)
        var environment: [String: String] = ["ZDOTDIR": rcDirectory.path]
        environment["WAKIL_USER_ZDOTDIR"] = base["ZDOTDIR"] ?? base["HOME"]
        // `-il`, not `-i`: an interactive LOGIN shell, which is what
        // Terminal.app runs and what makes `/etc/zprofile` — and
        // therefore `path_helper` — run at all. See
        // `terminalChildEnvironment` for why the base environment cannot
        // be relied on to carry PATH in the shipped app.
        return ([shell, "-il"], environment)
    case "bash":
        let rc = rcDirectory.appendingPathComponent("wakil-bashrc")
        try generatedRC(forShell: "bash").write(to: rc, atomically: true, encoding: .utf8)
        return ([shell, "--rcfile", rc.path, "-i"], [:])
    default:
        throw TerminalOpenError.unsupportedShell(shell)
    }
}

/// The environment one terminal pane's shell carries.
///
/// **It is Wakil's own process environment, plus the active context — and
/// the process environment is NOT the operator's login environment.** In a
/// bundled `Wakil.app` it is launchd's: no `/opt/homebrew/bin`, no
/// `AWS_PROFILE`, no `KUBECONFIG`. What reconstructs the operator's
/// environment is the **shell**, which is spawned as an interactive login
/// shell and sources their own profile chain from the generated rc —
/// exactly how Terminal.app gets there, and the reason `shellLaunch`
/// passes `-il`.
///
/// **That distinction is a shipped-artefact defect waiting to happen.**
/// Every test here inherits a terminal's environment, because `swift test`
/// runs from one, so a `-i` shell passes every test and ships with a PATH
/// that cannot find `kubectl`. Measure the build that ships.
///
/// The glossary says this pane carries *"the active environment's
/// variables and the org's credentials"*, and there is no literal referent
/// to copy: `wakilcore.Environment` is `{databases, api}` and the
/// capability layer holds no environment-variable map at all. The three
/// `WAKIL_*` variables are what make the shell aware of the context the
/// rest of the window resolves against.
///
/// **Keychain secrets are deliberately not exported, and the reason is
/// that they would not help.** The residue this pane exists for is
/// `kubectl get pods`, `aws s3 ls` and `docker ps` — named by #39 — and
/// every one of them authenticates from `~/.kube/config`,
/// `~/.aws/credentials` or the Docker socket. **Not one of them has ever
/// read `wakil:<org>:<ref>`**: those entries are DSNs and API credentials
/// consumed by `wakil-db` and `wakil-http`. So exporting them buys nothing
/// for the commands this pane is for, while widening Invariant 4's
/// boundary — which that invariant requires to be structurally
/// impossible to cross, not merely uncrossed.
///
/// Two further facts close it. There are **no names to export under**:
/// secrets are keyed by ref (`booking-staging-mysql`), no
/// variable-name convention exists anywhere, and inventing
/// `WAKIL_SECRET_<REF>` in Swift is the second implementation of a Go rule
/// that `resolve.go`'s own doc comment refuses. And it would be
/// **partial**: only the refs the active environment's `Databases` name
/// are enumerable at all, and a half-populated secret environment reads as
/// a complete one.
///
/// A *deliberate* way to fetch one credential in this pane — rather than
/// an ambient one — is the honest version of the idea, and it belongs
/// beside `wakil secrets set-api` in 2c-iv rather than here.
///
/// **This is still the opposite of the agent's shell**, which is the whole
/// reason no agent-reachable run ships: the harness builds its child
/// environment from nothing but `CLAUDE_CONFIG_DIR`,
/// `CLAUDE_CODE_OAUTH_TOKEN`, `HOME` and `PATH`.
///
/// **`TERM` is seeded, not forced.** A launchd- or Finder-launched
/// `Wakil.app` inherits no `TERM` at all — there is no controlling
/// terminal to inherit one from — so without this the shipped pane's
/// shell falls back to `dumb` even though every test here passes, because
/// `swift test` itself runs under a terminal that already has one. The
/// fallback is written BENEATH whatever `base` already carries, so a
/// caller (or the operator's own environment) that already set `TERM`
/// keeps its own value; only a `base` with no `TERM` at all gets Wakil's
/// default.
///
/// **Wired into `TerminalStore.performOpen`**, as the last layer over the
/// caller's `environment:` and `shellLaunch`'s own additions — this was
/// dead code until then, reachable only from tests, which meant no
/// shipped pane actually got `TERM` seeded. `org`/`project`/`environment`
/// are passed as empty strings from that call site, because `term_open`
/// has no source for the window's active context yet; a later task wires
/// that through, and until it does this function only contributes `TERM`
/// and the `COLUMNS`/`LINES` removal.
public func terminalChildEnvironment(
    org: String, project: String, environment: String,
    base: [String: String] = ProcessInfo.processInfo.environment
) -> [String: String] {
    var result = base
    // Absent means unset, never the empty string — the rule
    // `WakilWiring.childProcessEnvironment` already holds itself to.
    if !org.isEmpty { result["WAKIL_ORG"] = org }
    if !project.isEmpty { result["WAKIL_PROJECT"] = project }
    if !environment.isEmpty { result["WAKIL_ENVIRONMENT"] = environment }
    if result["TERM"] == nil { result["TERM"] = "xterm-256color" }
    // COLUMNS/LINES are deliberately NOT set: the winsize on the pty is
    // the authority, and a stale pair in the environment is exactly how a
    // resized pane starts drawing at the wrong width.
    result.removeValue(forKey: "COLUMNS")
    result.removeValue(forKey: "LINES")
    return result
}
