func readCompose(t *testing.T, name string) ComposeFacts {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", "compose", name))
	if err != nil {
		t.Fatal(err)
	}
	f, err := ParseCompose(b, name)
	if err != nil {
		t.Fatal(err)
	}
	return f
}

func TestParseComposeShortSyntax(t *testing.T) {
	f := readCompose(t, "short.yml")
	if len(f.Services) != 3 || f.Services[0].Name != "app" || f.Services[2].Name != "worker" {
		t.Fatalf("services in file order: %+v", f.Services)
	}
	app := f.Services[0]
	if !app.Build || f.Services[1].Build || f.Services[1].Image != "mysql:8" {
		t.Fatalf("build vs image: %+v", f.Services)
	}
	want := []ComposePort{
		{Published: "8080", Target: "80", Kind: PortFixed},
		{HostIP: "127.0.0.1", Published: "5432", Target: "5432", Kind: PortFixed},
		{Published: "${APP_PORT:-3000}", Target: "3000", Kind: PortVariable, Variables: []string{"APP_PORT"}},
		{Target: "9000", Kind: PortEphemeral},
		{HostIP: "::1", Published: "6379", Target: "6379", Protocol: "tcp", Kind: PortFixed},
		{Published: "8080", Target: "80", Protocol: "udp", Kind: PortFixed},
	}
	if !reflect.DeepEqual(app.Ports, want) {
		t.Fatalf("ports:\n got %+v\nwant %+v", app.Ports, want)
	}
	if f.Services[1].ContainerName != "initech_mysql" || f.Services[1].Ports[0].Published != "3306" {
		t.Fatalf("mysql: %+v", f.Services[1])
	}
}

func TestParseComposeLongSyntaxAndAnchors(t *testing.T) {
	f := readCompose(t, "long.yaml")
	cache := f.Services[0]
	if cache.Image != "redis:7" {
		t.Fatalf("merge key not followed: %+v", cache)
	}
	if p := cache.Ports[0]; !p.Long || p.Published != "6380" || p.Kind != PortFixed || p.Protocol != "tcp" || len(p.Extra) != 1 {
		t.Fatalf("long fixed: %+v", p)
	}
	if p := cache.Ports[1]; p.Kind != PortVariable || p.Variables[0] != "WEB_PORT" {
		t.Fatalf("long variable: %+v", p)
	}
	if p := cache.Ports[2]; p.Kind != PortEphemeral {
		t.Fatalf("long ephemeral: %+v", p)
	}
}

func TestComposeOverrideRemapsFixedPortsIntoTheBlock(t *testing.T) {
	f := readCompose(t, "short.yml")
	res, err := ComposeOverride(f, "INI-142", "api", 41200, []int{0, 1})
	if err != nil {
		t.Fatal(err)
	}
	if res.ProjectName != "ini-142-api" || res.File != ".wakil/compose.ports.yml" {
		t.Fatalf("names: %+v", res)
	}
	wantRemaps := []PortRemap{
		{"app", 8080, 41202, ""}, {"app", 5432, 41203, ""}, {"app", 6379, 41204, "tcp"},
		{"app", 8080, 41202, "udp"}, {"mysql", 3306, 41205, ""},
	}
	if !reflect.DeepEqual(res.Remaps, wantRemaps) {
		t.Fatalf("remaps:\n got %+v\nwant %+v", res.Remaps, wantRemaps)
	}
	wantYAML := `# Generated by Wakil for this workspace: fixed host ports moved into its block.
# Rewritten on every run; edit the recipe, not this file.
services:
  app:
    ports: !override
      - "41202:80"
      - "127.0.0.1:41203:5432"
      - "${APP_PORT:-3000}:3000"
      - "9000"
      - "[::1]:41204:6379/tcp"
      - "41202:80/udp"
  mysql:
    ports: !override
      - "41205:3306"
`
	if res.YAML != wantYAML {
		t.Fatalf("yaml:\n%s", res.YAML)
	}
	// What we write is YAML compose can read: it parses back to the same services.
	back, err := ParseCompose([]byte(res.YAML), "override")
	if err != nil || back.Services[0].Ports[1].Published != "41203" {
		t.Fatalf("override does not parse back: %v %+v", err, back)
	}
	var node yaml.Node
	if err := yaml.Unmarshal([]byte(res.YAML), &node); err != nil {
		t.Fatal(err)
	}
	if tag := mappingValue(mappingValue(mappingValue(node.Content[0], "services"), "app"), "ports").Tag; tag != "!override" {
		t.Fatalf("ports tag %q", tag)
	}
	if !reflect.DeepEqual(res.Variables, []ComposeVariable{{"app", "APP_PORT"}}) {
		t.Fatalf("variables %+v", res.Variables)
	}
	want := "api's compose file names its containers (container_name: initech_mysql in mysql), so it cannot run in two workspaces at once. Run it from one place with Bring to Main, or remove container_name from short.yml."
	if res.CannotRunTwice != want {
		t.Fatalf("sentence:\n%s", res.CannotRunTwice)
	}
}

func TestComposeOverrideLongSyntaxAndRanges(t *testing.T) {
	f := readCompose(t, "long.yaml")
	res, err := ComposeOverride(f, "w", "cache", 41300, nil)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(res.YAML, `      - {target: 6379, published: "41300", protocol: tcp, mode: "host"}`) {
		t.Fatalf("long entry:\n%s", res.YAML)
	}
	if !strings.Contains(res.YAML, `      - {target: 80, published: "${WEB_PORT}"}`) || !strings.Contains(res.YAML, `      - {target: 9229}`) {
		t.Fatalf("kept entries:\n%s", res.YAML)
	}
	if !strings.Contains(res.YAML, `  "odd name":`) || !strings.Contains(res.YAML, `published: "41301-41302", host_ip: "127.0.0.1"`) {
		t.Fatalf("range:\n%s", res.YAML)
	}
	if res.CannotRunTwice != "" {
		t.Fatal("no container_name here")
	}
	back, err := ParseCompose([]byte(res.YAML), "o")
	if err != nil || back.Services[0].Ports[0].Published != "41300" {
		t.Fatalf("parse back: %v %+v", err, back)
	}
}

func TestComposeOverrideNothingFixedAndBlockFull(t *testing.T) {
	f, _ := ParseCompose([]byte("services:\n  web:\n    ports: [\"${P}:80\"]\n"), "c.yml")
	res, err := ComposeOverride(f, "w", "r", 41200, nil)
	if err != nil || res.YAML != "" {
		t.Fatalf("nothing fixed means no file: %q %v", res.YAML, err)
	}
	f = readCompose(t, "short.yml")
	_, err = ComposeOverride(f, "w", "api", 41200, []int{0, 1, 2, 3, 4, 5, 6})
	if err == nil || !strings.Contains(err.Error(), "more fixed ports than the block") {
		t.Fatalf("full block: %v", err)
	}
	if _, err := ParseCompose([]byte("services: [\n"), "bad.yml"); err == nil || !strings.HasPrefix(err.Error(), "bad.yml is not valid YAML") {
		t.Fatalf("bad yaml: %v", err)
	}
}

func TestReservedOffsetsAndFindComposeFile(t *testing.T) {
	got := ReservedOffsets(map[string]string{"A": "$WAKIL_PORT", "B": "${WAKIL_PORT_3}", "C": "http://x:$WAKIL_PORT_API", "D": "$WAKIL_PORT_1"})
	if !reflect.DeepEqual(got, []int{0, 1, 3}) {
		t.Fatalf("offsets %v", got)
	}
	dir := t.TempDir()
	if FindComposeFile(dir) != "" {
		t.Fatal("none")
	}
	os.WriteFile(filepath.Join(dir, "docker-compose.yml"), nil, 0o600)
	os.WriteFile(filepath.Join(dir, "compose.yaml"), nil, 0o600)
	if FindComposeFile(dir) != "compose.yaml" {
		t.Fatal("compose's own order")
	}
}
