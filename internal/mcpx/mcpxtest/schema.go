// Package mcpxtest holds assertions that need a live MCP client/server
// round trip and are therefore shared by every cmd/ server's test suite.
//
// It is a separate package from mcpx, rather than a _test.go file in it,
// for two reasons: every cmd/ server is `package main`, so a helper in one
// server's test files is unreachable from the other four, and this code
// imports "testing", which must never be linked into a shipped binary.
// Nothing outside a _test.go file may import this package.
package mcpxtest

import (
	"context"
	"encoding/json"
	"sort"
	"testing"

	"github.com/modelcontextprotocol/go-sdk/mcp"
)

// AssertObjectOutputSchemas connects s to an in-memory MCP client, reads
// every tool the server advertises through ListTools, and fails t for any
// tool whose advertised outputSchema is not a top-level "type":"object".
//
// WHY this is worth a real round trip in all five servers instead of a
// code-review note: the outputSchema is generated by the SDK from the
// handler's typed Out, so nothing at the registration site looks wrong. A
// slice-typed Out compiles, satisfies every handler-level unit test in this
// repo (they call the handler, or CallTool through a Go client that
// tolerates the shape), and only fails at the protocol layer in front of a
// validating client. That is how wakil-db's list_databases and list_tables
// and wakil-ctx's list_sessions all shipped unusable and had to be caught
// by hand in the Phase 1 acceptance run. This assertion is the one that
// would have caught them.
//
// The required type is the exact JSON string "object", not a union such as
// ["null","object"]: MCP requires structuredContent to BE an object, so a
// schema that also admits null admits a violation. A tool advertising NO
// output schema at all (which is what declaring Out as `any` produces)
// fails too — forfeiting the schema is not an acceptable way to satisfy
// this check.
//
// wantTools is the exact set of tool names the server must advertise, and
// it is asserted rather than merely informational so the check can never
// pass vacuously: a server that registered nothing, or a ListTools that
// silently came back empty, would otherwise trivially satisfy "no tool has
// a bad schema".
func AssertObjectOutputSchemas(t *testing.T, s *mcp.Server, wantTools []string) {
	t.Helper()
	ctx := context.Background()

	serverTransport, clientTransport := mcp.NewInMemoryTransports()
	ss, err := s.Connect(ctx, serverTransport, nil)
	if err != nil {
		t.Fatalf("server Connect: %v", err)
	}
	t.Cleanup(func() { ss.Close() })

	client := mcp.NewClient(&mcp.Implementation{Name: "mcpxtest-schema-client", Version: "0.0.0"}, nil)
	cs, err := client.Connect(ctx, clientTransport, nil)
	if err != nil {
		t.Fatalf("client Connect: %v", err)
	}
	t.Cleanup(func() { cs.Close() })

	res, err := cs.ListTools(ctx, nil)
	if err != nil {
		t.Fatalf("ListTools: %v", err)
	}

	var gotTools []string
	for _, tool := range res.Tools {
		gotTools = append(gotTools, tool.Name)
	}
	sort.Strings(gotTools)
	want := append([]string(nil), wantTools...)
	sort.Strings(want)
	if len(gotTools) != len(want) {
		t.Fatalf("ListTools advertised %d tools %v, want %d %v", len(gotTools), gotTools, len(want), want)
	}
	for i := range want {
		if gotTools[i] != want[i] {
			t.Fatalf("ListTools advertised %v, want %v", gotTools, want)
		}
	}

	for _, tool := range res.Tools {
		if tool.OutputSchema == nil {
			t.Errorf("tool %q advertises no outputSchema at all; declare a struct-typed Out, not `any`", tool.Name)
			continue
		}
		// Round-trip through JSON rather than reading the SDK's schema
		// struct fields: the wire form is what a client validates against,
		// and it is also what a future SDK version could change under us.
		raw, err := json.Marshal(tool.OutputSchema)
		if err != nil {
			t.Errorf("tool %q: marshal OutputSchema: %v", tool.Name, err)
			continue
		}
		var schema map[string]any
		if err := json.Unmarshal(raw, &schema); err != nil {
			t.Errorf("tool %q: unmarshal OutputSchema: %v", tool.Name, err)
			continue
		}
		if schema["type"] != "object" {
			t.Errorf("tool %q advertises outputSchema type %#v, want the exact string \"object\": %s\n"+
				"MCP requires structuredContent to be a JSON object; wrap the handler's Out in a struct "+
				"(see internal/mcpx's ToolErr doc comment)", tool.Name, schema["type"], raw)
		}
	}
}
